# Escape sequence characters example: \n, \t, \' , \\ etc.
                            # newline, tab, singlequote, backslash
## Escape Sequence      Meaning
# \n                    Newline (Moves the cursor to the next line)
# \t                    Horizontal Tab (Inserts a tab space)
# \\                    Backslash (Inserts a literal backslash)
# \'                    Single Quote (Inserts ' inside single-quoted strings)
# \"                    Double Quote (Inserts " inside double-quoted strings)
# \r                    Carriage Return (Moves the cursor to the beginning of the line)
# \b                    Backspace (Deletes the previous character)
# \a                    ASCII Bell (Triggers a system alert sound)
# \f                    ASCII Formfeed (Advances to the next page)
# \v                    ASCII Vertical Tab
# \<newline>            Ignored End of Line (Continues the string on the next line without a line break)
# \ooo                  Octal value (Character based on up to 3 octal digits)